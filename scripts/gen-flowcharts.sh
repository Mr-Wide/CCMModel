## RootedAsync

`RootedAsync` from the same paper: the P1Tree DFS run agent by agent, under
synchronous rounds or the paper's asynchronous schedule. Every agent is its own
process. One activation is one Communicate-Compute-Move cycle: the agent reads
the agents at its node, writes its own memory and at most one other's, and
leaves along at most one port. Under `Interleaved` the read and the write are
separate steps with other agents acting in between.

One agent leads. It settles the highest unsettled ID at each new node, sends
the group out in probe batches, concludes each probe by rules R1 to R3c from
what the group remembers (never from the simulator's ownership index), and
decides the next edge and who vacates. Members act on its numbered commands.
The simulator checks every conclusion against the truth and stops on any
disagreement. When nobody is left unsettled the lead role passes to a scout
and the scouts walk the tree home, each dropping off at the node it owns.

```mermaid
flowchart TD
    A["simulate()"] --> B{"schedule?"}
    B -- synchronous --> S1["run_synchronous(): every agent, one round"]
    B -- random --> S2["run_asynchronous(): one agent at a time"]
    B -- interleaved --> S3["run_interleaved(): look now, write later"]
    S1 --> C["activate(): one agent, one cycle"]
    S2 --> C
    S3 --> C
    C --> T{"lead, or task?"}
    T -- "member, idle" --> F["follow(): carry out the newest command"]
    T -- probing --> P["probe_step(): one hop of R1-R3"]
    T -- errand --> E["errand_step(): a V2-V5 excursion"]
    T -- lead --> G["arrive(): settle the highest ID, or D4"]
    G --> U{"anyone unsettled?"}
    U -- yes --> PL["plan_probe(): batches, scatter mode"]
    PL --> FB["finish_batch(): conclude each probe"]
    FB --> M{"ports left?"}
    M -- yes --> FB
    M -- no --> D["decide(): node type, next edge, who vacates"]
    D --> V["errand_done(): V2-V5 outcome"]
    V --> MV["begin_move(): group leaves, lead last"]
    MV -- next node --> G
    U -- no --> R["begin_retrace(): lead passes to a scout"]
    R --> RS["retrace_step(): next node home"]
    RS --> RT{"scouts still travelling?"}
    RT -- yes --> RS
    RT -- no --> Z["Termination::Completed"]

    FB -. rules .-> RV["resolve(): R1-R3c"]
```

HEADER

