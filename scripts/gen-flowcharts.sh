## P1Tree

`DFS_P1Tree` from Pattanayak, Kshemkalyani, Kumar, Molla and Sharma, *Optimal
Dispersion Under Asynchrony*. A DFS that builds a **port-one tree**: every
vertex ends up with an incident tree edge carrying port 1 at one of its ends.
Edges are preferred `tp1 > t11 ~ t1q > tpq`, and a node reached only through a
`tpq` edge is parked as `partiallyVisited` until its port-1 neighbour comes to
claim it.

Two details carry the `O(k)` bound, and losing either makes the cost scale with
the graph instead of with the agents:

- `neighbourhood_search` **stops at the first batch that finds somewhere to go**.
  Remark 1 bounds the search by the agent count, not the degree, because at most
  `k` nodes are ever occupied, so while any agent is unsettled some probed
  neighbour must be empty.
- `traverse` **stops at dispersion**. Section 5: "the process continues until no
  unsettled agents remain". The tree at that moment need not yet be a P1Tree â€”
  a parked node may still hold a `tpq` parent edge â€” and that is fine, because
  dispersion is the goal.

`traverse` has two ways out, dispersion or the root being popped, and `run`
follows either with `retrace`, which walks the scouts home along the tree: a
depth-first tour from wherever the head finished, one edge per step, dropping
each scout at its home. Vacated scouts travel with the group throughout, so no
agent ever moves except along an edge. A run that hits the round limit stops without
retrace.

```mermaid
flowchart TD
    A["run() / simulate()"] --> B["settle_highest_at(root)"]
    B --> C["traverse()"]
    C --> D{"dispersed?"}
    D -- yes --> R["retrace()"]
    D -- no --> E["neighbourhood_search()"]

    subgraph probe ["parallel probe, one batch at a time"]
        E --> E1["probe_party() picks the scouts"]
        E1 --> E2["next batch: scouts go out, state_of() / probe_detour(), and back"]
        E2 --> E3{"somewhere to go, or no ports left?"}
        E3 -- no --> E2
    end

    E3 -- yes --> E4{"choose_next_edge()"}
    E4 -- found --> F{"must_defer()?"}
    E4 -- exhausted --> G{"awaits_port_one()?"}

    F -- yes --> P["mark partiallyVisited"]
    F -- no --> H["advance(): move, settle_highest_at() if unvisited, set_parent()"]
    G -- yes --> P
    G -- no --> Q["mark fullyVisited"]

    H --> K["apply_can_vacate() / apply_parent_vacate()"]
    K --> D

    P --> L["apply_can_vacate()"]
    Q --> L
    L --> M["backtrack()"]
    M --> N{"root popped?"}
    N -- no --> D
    N -- yes --> R

    R --> S["tour() of the tree from the head, drop each scout at its home"]
    S --> Z["Termination::Completed"]
```

